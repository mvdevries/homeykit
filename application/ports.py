from collections.abc import Callable, Iterable, Mapping
from typing import Any, Protocol

from ..domain.homey_device import HomeyDevice

type LocalAddressFinder = Callable[[], str | None]


class SettingsStorage(Protocol):
    def get(self, key: str) -> Any: ...

    async def set(self, key: str, value: Any) -> None: ...

    async def unset(self, key: str) -> None: ...


class ExposedDevicesRepository(Protocol):
    def read_exposed_device_ids(self) -> frozenset[str]: ...

    async def save_exposed_device_ids(self, device_ids: Iterable[str]) -> None: ...


class AccessoryIdRepository(Protocol):
    async def get_or_assign_accessory_id(self, device_id: str) -> int: ...


class BridgeNameRepository(Protocol):
    def read_custom_name(self) -> str | None: ...

    async def save_custom_name(self, name: str) -> None: ...

    async def clear_custom_name(self) -> None: ...


class PincodeRepository(Protocol):
    def read_pincode(self) -> str | None: ...

    async def save_pincode(self, pincode: str) -> None: ...


class StartupDelayRepository(Protocol):
    def read_enabled(self) -> bool: ...

    def read_seconds(self) -> int | None: ...

    async def save(self, enabled: bool, seconds: int) -> None: ...


class DevicesGateway(Protocol):
    async def fetch_all_devices(self) -> dict[str, HomeyDevice]: ...

    async def fetch_device(self, device_id: str) -> HomeyDevice: ...

    async def fetch_zone_names(self) -> Mapping[str, str]: ...

    async def fetch_icon_svg(self, icon_path: str) -> str: ...

    async def fetch_homey_name(self) -> str | None: ...

    async def set_capability_value(
        self, device_id: str, capability_id: str, value: Any
    ) -> None: ...


class DeviceSupport(Protocol):
    def is_supported(self, device: HomeyDevice) -> bool: ...


class HomeKitBridge(Protocol):
    @property
    def name(self) -> str: ...

    @property
    def address(self) -> str: ...

    @property
    def is_paired(self) -> bool: ...

    @property
    def pincode(self) -> str: ...

    @property
    def exposed_device_ids(self) -> frozenset[str]: ...

    def qr_code_svg(self) -> str: ...

    def set_device_written_listener(self, listener: Callable[[str], None]) -> None: ...

    def add_device(self, device: HomeyDevice, accessory_id: int) -> None: ...

    def remove_device(self, device_id: str) -> None: ...

    def update_device(self, device: HomeyDevice) -> None: ...

    def announce_configuration_change(self) -> None: ...

    def apply_pincode(self, pincode: str) -> None: ...

    async def publish(self) -> None: ...

    async def stop(self) -> None: ...


class HomeKitBridgeFactory(Protocol):
    def create(self, *, name: str, address: str, pincode: str) -> HomeKitBridge: ...
